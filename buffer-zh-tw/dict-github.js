// 每次處理新內容前執行：標記不翻譯區塊，並讓時間標籤 <relative-time> 自己以中文顯示
// （它的文字在 Shadow DOM 裡會一直重算，用 lang="zh-TW" 讓瀏覽器內建的中文日期格式接手）。
function GITHUB_ZH_HOOK(root) {
  var scope = root && root.querySelectorAll ? root : document;
  if (root && root.nodeType === 1 && root.matches && root.matches(GITHUB_ZH_SKIP)) root.setAttribute("data-zh-skip", "");
  scope.querySelectorAll(GITHUB_ZH_SKIP).forEach(function (el) {
    if (!el.hasAttribute("data-zh-skip")) el.setAttribute("data-zh-skip", "");
  });
  scope.querySelectorAll("relative-time:not([lang='zh-TW']), time-ago:not([lang='zh-TW'])").forEach(function (el) {
    el.setAttribute("lang", "zh-TW");
  });
}
