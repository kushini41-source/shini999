function MONTH_NUM(mo) {
  return ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"].indexOf(mo.slice(0, 3).toLowerCase()) + 1;
}

// 把句子裡的英文日期、時間換成中文，例如 "March 12 at 9:42pm (GMT)" → "3 月 12 日 下午 9:42 (GMT)"
function ZH_DATE(s) {
  var DAYS = { monday: "星期一", tuesday: "星期二", wednesday: "星期三", thursday: "星期四", friday: "星期五", saturday: "星期六", sunday: "星期日" };
  return s
    .replace(/\b(Monday|Tuesday|Wednesday|Thursday|Friday|Saturday|Sunday),?\s*/gi, function (m, d) { return DAYS[d.toLowerCase()] + " "; })
    .replace(/\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Sept|Oct|Nov|Dec)[a-z]*\.? (\d{1,2})(?:st|nd|rd|th)?(?:,? (\d{4}))?/gi, function (m, mo, d, y) {
      return (y ? y + " 年 " : "") + MONTH_NUM(mo) + " 月 " + d + " 日";
    })
    .replace(/(\d{1,2})(?::(\d{2}))?\s*(am|pm)\b/gi, function (m, h, mi, ap) {
      return (ap.toLowerCase() === "am" ? "上午 " : "下午 ") + h + ":" + (mi || "00");
    })
    .replace(/\s+at\s+/gi, " ")
    .replace(/^at\s+/i, "")
    .replace(/^on\s+/i, "");
}
